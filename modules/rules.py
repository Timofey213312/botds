# Ключевые слова для поиска канала правил
RULES_CHANNEL_KEYWORDS = ('правил', 'rules')
EMBED_COLOR = 0x9000FF


def _find_rules_channel(guild):
    """Поиск канала правил по названию"""
    for channel in guild.text_channels:
        name = (channel.name or '').lower()
        for kw in RULES_CHANNEL_KEYWORDS:
            if kw in name:
                return channel
    return None


